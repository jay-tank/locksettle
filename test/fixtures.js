"use strict";

// Builds throwaway git repositories with REAL merge conflicts in lockfiles (two branches edit
// the same lockfile lines, then `git merge` stops with conflicts), plus hostile repositories.
// Used by the Node test and the in-editor test.

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const GIT_ENV = Object.assign({}, process.env, {
  GIT_CONFIG_GLOBAL: "/dev/null",
  GIT_CONFIG_SYSTEM: "/dev/null",
  GIT_CONFIG_NOSYSTEM: "1",
  GIT_AUTHOR_NAME: "Fixture",
  GIT_AUTHOR_EMAIL: "fixture@example.invalid",
  GIT_COMMITTER_NAME: "Fixture",
  GIT_COMMITTER_EMAIL: "fixture@example.invalid",
});

function git(cwd, ...args) {
  return execFileSync("git", ["-c", "core.fsmonitor=", "-c", "core.hooksPath=/dev/null"].concat(args), { cwd, env: GIT_ENV, stdio: ["ignore", "pipe", "pipe"] }).toString("utf8");
}

function gitMayFail(cwd, ...args) {
  try {
    return git(cwd, ...args);
  } catch (e) {
    return String(e.stdout || "");
  }
}

function write(root, rel, content) {
  const abs = path.join(root, rel);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content);
}

/** package.json with a far-apart dependency block so both branches auto-merge cleanly. */
function packageJson(name, a, b) {
  const lines = ['{', `  "name": "${name}",`, '  "version": "1.0.0",', '  "dependencies": {', `    "left-pad": "${a}",`];
  for (let i = 0; i < 8; i++) lines.push(`    "filler-${i}": "1.0.${i}",`);
  lines.push(`    "right-pad": "${b}"`, "  }", "}", "");
  return lines.join("\n");
}

function packageLock(name, a, b) {
  return JSON.stringify({ name, version: "1.0.0", lockfileVersion: 3, requires: true, packages: { "": { name, dependencies: { "left-pad": a, "right-pad": b } }, "node_modules/pad": { version: a + "+" + b } } }, null, 2) + "\n";
}

function yarnLock(v) {
  return "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\nleft-pad@^1.0.0:\n  version \"" + v + "\"\n  resolved \"https://registry.yarnpkg.com/left-pad/-/left-pad-" + v + ".tgz\"\n";
}

function poetryLock(v) {
  return "# This file is automatically @generated by Poetry 1.8.3 and should not be changed by hand.\n\n[[package]]\nname = \"requests\"\nversion = \"" + v + "\"\n\n[metadata]\nlock-version = \"2.0\"\ncontent-hash = \"" + v + "\"\n";
}

/**
 * Two branches: "main" (ours) and "feature" (theirs). `edits(side)` returns {rel: content}
 * written on that branch. After the merge the repo is left in the conflicted state.
 */
function makeConflictRepo(root, baseFiles, oursFiles, theirsFiles) {
  fs.mkdirSync(root, { recursive: true });
  git(root, "init", "-q", "-b", "main");
  for (const [rel, c] of Object.entries(baseFiles)) write(root, rel, c);
  git(root, "add", "-A");
  git(root, "commit", "-q", "-m", "base");
  git(root, "checkout", "-q", "-b", "feature");
  for (const [rel, c] of Object.entries(theirsFiles)) write(root, rel, c);
  git(root, "add", "-A");
  git(root, "commit", "-q", "-m", "feature");
  git(root, "checkout", "-q", "main");
  for (const [rel, c] of Object.entries(oursFiles)) write(root, rel, c);
  git(root, "add", "-A");
  git(root, "commit", "-q", "-m", "main");
  gitMayFail(root, "merge", "--no-edit", "feature");
  return root;
}

function makeMainRepo(root) {
  const base = {
    "package.json": packageJson("app", "1.0.0", "1.0.0"),
    "package-lock.json": packageLock("app", "1.0.0", "1.0.0"),
    "packages/web/package.json": packageJson("web", "1.0.0", "1.0.0"),
    "packages/web/package-lock.json": packageLock("web", "1.0.0", "1.0.0"),
    "-weird/package.json": packageJson("weird", "1.0.0", "1.0.0"),
    "-weird/yarn.lock": yarnLock("1.0.0"),
    "py/pyproject.toml": "[tool.poetry]\nname = \"py\"\n\n[tool.poetry.dependencies]\nrequests = \"^2\"\n",
    "py/poetry.lock": poetryLock("2.0.0"),
    "docs/notes.json": JSON.stringify({ text: "<<<<<<< HEAD\n=======\n>>>>>>> x" }) + "\n",
    "README.md": "# app\n",
  };
  const ours = {
    "package.json": packageJson("app", "1.1.0", "1.0.0"),
    "package-lock.json": packageLock("app", "1.1.0", "1.0.0"),
    "packages/web/package.json": packageJson("web", "2.0.0", "1.0.0"),
    "packages/web/package-lock.json": packageLock("web", "2.0.0", "1.0.0"),
    "-weird/yarn.lock": yarnLock("1.1.0"),
    "py/poetry.lock": poetryLock("2.1.0"),
  };
  const theirs = {
    "package.json": packageJson("app", "1.0.0", "1.2.0"),
    "package-lock.json": packageLock("app", "1.0.0", "1.2.0"),
    "packages/web/package.json": packageJson("web", "3.0.0", "1.0.0"),
    "packages/web/package-lock.json": packageLock("web", "3.0.0", "1.0.0"),
    "-weird/yarn.lock": yarnLock("1.2.0"),
    "py/poetry.lock": poetryLock("2.2.0"),
  };
  return makeConflictRepo(root, base, ours, theirs);
}

/**
 * Hostile repo: a real Cargo.lock conflict and a Gemfile.lock conflict, then repo-local config
 * that would run programs (fsmonitor, pager, external diff, post-checkout hook, a clean/smudge
 * filter on Gemfile.lock), and a lockfile symlinked to a conflicted file outside the workspace.
 */
function makeHostileRepo(root, outsideDir, markerDir) {
  fs.mkdirSync(outsideDir, { recursive: true });
  fs.mkdirSync(markerDir, { recursive: true });
  const cargoToml = "[package]\nname = \"h\"\nversion = \"0.1.0\"\n";
  const cargoLock = (v) => "# This file is automatically @generated by Cargo.\nversion = 3\n\n[[package]]\nname = \"serde\"\nversion = \"" + v + "\"\n";
  const gemLock = (v) => "GEM\n  remote: https://rubygems.org/\n  specs:\n    rake (" + v + ")\n\nBUNDLED WITH\n   2.5.0\n";
  makeConflictRepo(
    root,
    { "Cargo.toml": cargoToml, "Cargo.lock": cargoLock("1.0.0"), "gems/Gemfile": "source 'https://rubygems.org'\ngem 'rake'\n", "gems/Gemfile.lock": gemLock("13.0.0") },
    { "Cargo.lock": cargoLock("1.0.1"), "gems/Gemfile.lock": gemLock("13.0.1") },
    { "Cargo.lock": cargoLock("1.0.2"), "gems/Gemfile.lock": gemLock("13.0.2") }
  );
  // Outside conflicted lockfile reached through a symlink inside the repo.
  write(outsideDir, "package-lock.json", "<<<<<<< HEAD\n{}\n=======\n{}\n>>>>>>> x\n");
  write(root, "linked/package.json", "{\"name\":\"linked\"}\n");
  fs.symlinkSync(path.join(outsideDir, "package-lock.json"), path.join(root, "linked", "package-lock.json"));
  // Hostile configuration, set after the conflict exists.
  const m = (n) => path.join(markerDir, n);
  git(root, "config", "core.fsmonitor", `touch '${m("fsmonitor")}'; echo`);
  git(root, "config", "core.pager", `touch '${m("pager")}'; cat`);
  git(root, "config", "diff.external", `sh -c "touch '${m("extdiff")}'"`);
  git(root, "config", "filter.evil.clean", `sh -c "touch '${m("filter-clean")}'; cat"`);
  git(root, "config", "filter.evil.smudge", `sh -c "touch '${m("filter-smudge")}'; cat"`);
  fs.writeFileSync(path.join(root, ".gitattributes"), "gems/Gemfile.lock filter=evil\n");
  const hook = path.join(root, ".git", "hooks", "post-checkout");
  fs.writeFileSync(hook, `#!/bin/sh\ntouch '${m("post-checkout")}'\n`);
  fs.chmodSync(hook, 0o755);
  return root;
}

/** Repo whose core.worktree points outside (set after the conflict exists). */
function makeWorktreeEscapeRepo(root, outsideWorktree) {
  fs.mkdirSync(outsideWorktree, { recursive: true });
  makeConflictRepo(
    root,
    { "go.mod": "module example.com/x\n\ngo 1.22\n", "go.sum": "example.com/a v1.0.0 h1:AAA=\n" },
    { "go.sum": "example.com/a v1.0.1 h1:BBB=\n" },
    { "go.sum": "example.com/a v1.0.2 h1:CCC=\n" }
  );
  git(root, "config", "core.worktree", outsideWorktree);
  return root;
}

module.exports = { git, write, makeMainRepo, makeHostileRepo, makeWorktreeEscapeRepo, makeConflictRepo, packageLock, GIT_ENV };
