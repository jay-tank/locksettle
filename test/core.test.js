"use strict";

// Plain Node tests for core.js. Run: node test/core.test.js

const fs = require("fs");
const os = require("os");
const path = require("path");
const core = require("../core");
const { git, makeMainRepo, makeHostileRepo, makeWorktreeEscapeRepo } = require("./fixtures");

let pass = 0;
let fail = 0;
function check(name, cond, detail) {
  if (cond) {
    pass++;
    console.log("PASS " + name);
  } else {
    fail++;
    console.log("FAIL " + name + (detail !== undefined ? " :: " + detail : ""));
  }
}
const eq = (a, b) => JSON.stringify(a) === JSON.stringify(b);

async function main() {
  // --- ecosystem detection ---
  const expect = {
    "package-lock.json": ["npm", "package.json"],
    "npm-shrinkwrap.json": ["npm", "package.json"],
    "yarn.lock": ["yarn", "package.json"],
    "pnpm-lock.yaml": ["pnpm", "package.json"],
    "poetry.lock": ["poetry", "pyproject.toml"],
    "uv.lock": ["uv", "pyproject.toml"],
    "Cargo.lock": ["cargo", "Cargo.toml"],
    "go.sum": ["go", "go.mod"],
    "composer.lock": ["composer", "composer.json"],
    "Gemfile.lock": ["bundler", "Gemfile"],
    "Pipfile.lock": ["pipenv", "Pipfile"],
  };
  for (const [n, [eco, man]] of Object.entries(expect)) {
    const i = core.lockfileInfo("/x/y/" + n);
    check("ecosystem " + n + " -> " + eco, i && i.ecosystem === eco && i.manifest === man, JSON.stringify(i));
  }
  for (const n of ["package.json", "cargo.lock", "yarn.lock.bak", "go.mod", "Package-Lock.json", "gemfile.lock", ""]) {
    check("not a lockfile: '" + n + "'", core.lockfileInfo("/x/" + n) === null);
  }

  // --- marker detection ---
  const real = "a\n<<<<<<< HEAD\nours\n=======\ntheirs\n>>>>>>> feature\nb\n";
  check("real conflict block found", eq(core.findConflictBlocks(real), [{ start: 1, mid: 3, end: 5 }]));
  const diff3 = "<<<<<<< ours\nx\n||||||| base\ny\n=======\nz\n>>>>>>> theirs\n";
  check("diff3 block found", core.findConflictBlocks(diff3).length === 1);
  check("CRLF block found", core.hasConflictMarkers("<<<<<<< HEAD\r\nx\r\n=======\r\ny\r\n>>>>>>> b\r\n"));
  check("two blocks counted", core.findConflictBlocks(real + real).length === 2);
  check("bare markers without labels", core.hasConflictMarkers("<<<<<<<\nx\n=======\ny\n>>>>>>>\n"));
  check("marker inside a JSON string ignored", !core.hasConflictMarkers(JSON.stringify({ t: "<<<<<<< HEAD\n=======\n>>>>>>> x" })));
  check("indented markers ignored", !core.hasConflictMarkers("  <<<<<<< HEAD\n  =======\n  >>>>>>> x\n"));
  check("quoted markers ignored", !core.hasConflictMarkers('"<<<<<<< HEAD"\n"======="\n">>>>>>> x"\n'));
  check("incomplete block ignored (no end)", !core.hasConflictMarkers("<<<<<<< HEAD\nx\n=======\ny\n"));
  check("incomplete block ignored (no middle)", !core.hasConflictMarkers("<<<<<<< HEAD\nx\n>>>>>>> y\n"));
  check("eight < is not a marker", !core.hasConflictMarkers("<<<<<<<< HEAD\nx\n=======\ny\n>>>>>>> z\n"));
  check("setext heading ======= alone ignored", !core.hasConflictMarkers("Title\n=======\n"));
  check("marker glued to text ignored", !core.hasConflictMarkers("<<<<<<<HEAD\nx\n=======\ny\n>>>>>>>z\n"));
  check("ours side extraction", core.oursSide("h\n<<<<<<< a\nO\n=======\nT\n>>>>>>> b\nz") === "h\nO\nz");

  // --- yarn berry detection ---
  check("berry via packageManager yarn@4", core.detectYarnFlavor({ packageJsonText: '{"packageManager": "yarn@4.1.0"}' }) === "berry");
  check("classic via packageManager yarn@1", core.detectYarnFlavor({ packageJsonText: '{"packageManager":"yarn@1.22.19"}', hasYarnrcYml: true }) === "classic");
  check("berry via .yarnrc.yml", core.detectYarnFlavor({ packageJsonText: "{}", hasYarnrcYml: true }) === "berry");
  check("berry via __metadata lockfile", core.detectYarnFlavor({ lockText: '__metadata:\n  version: 8\n' }) === "berry");
  check("classic via v1 header", core.detectYarnFlavor({ lockText: "# yarn lockfile v1\n" }) === "classic");
  check("classic by default", core.detectYarnFlavor({}) === "classic");
  check("setting forces berry", core.detectYarnFlavor({ lockText: "# yarn lockfile v1\n", setting: "berry" }) === "berry");
  check("packageManager pnpm is not yarn berry", core.detectYarnFlavor({ packageJsonText: '{"packageManager":"pnpm@9.0.0"}' }) === "classic");

  // --- poetry detection ---
  check("poetry 1 header", core.detectPoetryMajor("# This file is automatically @generated by Poetry 1.8.3 and should not be changed by hand.") === 1);
  check("poetry 2 header", core.detectPoetryMajor("# This file is automatically @generated by Poetry 2.1.3 and should not be changed by hand.") === 2);
  check("poetry unknown -> 2", core.detectPoetryMajor("[[package]]") === 2);
  check("poetry setting 1 wins", core.detectPoetryMajor("@generated by Poetry 2.0.0", "1") === 1);

  // --- command table ---
  const cmd = (eco, o) => core.resolveCommand(eco, o).argv.join(" ");
  check("npm command", cmd("npm") === "npm install --package-lock-only --ignore-scripts");
  check("yarn classic command", cmd("yarn", { yarnFlavor: "classic" }) === "yarn install --ignore-scripts");
  check("yarn berry command", cmd("yarn", { yarnFlavor: "berry" }) === "yarn install --mode=update-lockfile");
  check("pnpm command", cmd("pnpm") === "pnpm install --lockfile-only --ignore-scripts");
  check("poetry 1 command", cmd("poetry", { poetryMajor: 1 }) === "poetry lock --no-update");
  check("poetry 2 command", cmd("poetry", { poetryMajor: 2 }) === "poetry lock");
  check("uv command", cmd("uv") === "uv lock");
  check("cargo command (not generate-lockfile)", cmd("cargo") === "cargo update --workspace");
  check("go command", cmd("go") === "go mod tidy");
  check("composer command", cmd("composer") === "composer update --lock --no-install --no-scripts");
  check("bundler command", cmd("bundler") === "bundle lock");
  check("pipenv command", cmd("pipenv") === "pipenv lock");
  check("every ecosystem has a command and base", core.ECOSYSTEMS.every((e) => core.resolveCommand(e, {}).argv.length > 0 && ["keep", "ours"].includes(core.resolveBase(e, {}))));
  check("default table is a copy", (() => { const a = core.resolveCommand("npm", {}).argv; a.push("x"); return cmd("npm") === "npm install --package-lock-only --ignore-scripts"; })());
  check("string override split", eq(core.resolveCommand("npm", { overrides: { npm: 'node -e "console.log(1)"' } }).argv, ["node", "-e", "console.log(1)"]));
  check("array override used as is", eq(core.resolveCommand("go", { overrides: { go: ["go", "mod", "tidy", "-e"] } }).argv, ["go", "mod", "tidy", "-e"]));
  check("empty override ignored", cmd("go", { overrides: { go: "   " } }) === "go mod tidy");
  check("invalid array override ignored", cmd("go", { overrides: { go: [1, 2] } }) === "go mod tidy");
  check("yarn override applies to berry", eq(core.resolveCommand("yarn", { yarnFlavor: "berry", overrides: { yarn: "yarn x" } }).argv, ["yarn", "x"]));
  check("yarnBerry override wins for berry", eq(core.resolveCommand("yarn", { yarnFlavor: "berry", overrides: { yarn: "yarn x", yarnBerry: "yarn y" } }).argv, ["yarn", "y"]));
  check("yarnBerry override not used for classic", cmd("yarn", { yarnFlavor: "classic", overrides: { yarnBerry: "yarn y" } }) === "yarn install --ignore-scripts");
  check("split: single quotes literal", eq(core.splitCommand("a 'b c' \"d \\\" e\""), ["a", "b c", 'd " e']));
  check("split: shell metachars stay literal", eq(core.splitCommand("npm install; rm -rf /"), ["npm", "install;", "rm", "-rf", "/"]));
  check("split: unterminated quote rejected", core.splitCommand("a 'b") === null);
  check("split: empty rejected", core.splitCommand("") === null);
  check("format command quotes", core.formatCommand(["node", "-e", "a b"]) === "node -e 'a b'");

  // --- base strategy ---
  check("npm base keep", core.resolveBase("npm", {}) === "keep");
  check("yarn base keep", core.resolveBase("yarn", {}) === "keep");
  check("pnpm base keep", core.resolveBase("pnpm", {}) === "keep");
  for (const e of ["poetry", "uv", "cargo", "go", "composer", "bundler", "pipenv"]) check(e + " base ours", core.resolveBase(e, {}) === "ours");
  check("base override theirs", core.resolveBase("cargo", { cargo: "theirs" }) === "theirs");
  check("base override junk ignored", core.resolveBase("npm", { npm: "rm -rf" }) === "keep");
  check("plan mentions checkout for ours", /git checkout --ours -- Cargo\.lock/.test(core.describePlan({ lockName: "Cargo.lock", relDir: ".", base: "ours", argv: ["cargo", "update", "--workspace"] })));
  check("plan keeps markers for keep", /Keep package-lock\.json/.test(core.describePlan({ lockName: "package-lock.json", relDir: "a", base: "keep", argv: ["npm"] })));
  {
    const ours = core.describePlan({ lockName: "Cargo.lock", relDir: ".", base: "ours", argv: ["cargo", "update", "--workspace"], manifest: "Cargo.toml" });
    check("ours plan warns the other branch's lockfile-only pins may change", /The other branch's Cargo\.lock changes are dropped and re-resolved from Cargo\.toml\./.test(ours) && /pinned only in Cargo\.lock \(not in Cargo\.toml\) may change/.test(ours), ours);
    check("ours plan tells to review the diff", /Review the lockfile diff before you commit\./.test(ours), ours);
    check("ours plan explains the rebase swap", /during a rebase "ours" is the branch you are rebasing onto/.test(ours), ours);
    const theirs = core.describePlan({ lockName: "poetry.lock", relDir: "py", base: "theirs", argv: ["poetry", "lock"], manifest: "pyproject.toml" });
    check("theirs plan says your side's pins are dropped", /Your side's poetry\.lock changes are dropped/.test(theirs) && /Folder: py/.test(theirs), theirs);
    const keep = core.describePlan({ lockName: "package-lock.json", relDir: ".", base: "keep", argv: ["npm"], manifest: "package.json" });
    check("keep plan has no pin warning", !/dropped/.test(keep) && !/Review the lockfile diff/.test(keep), keep);
    check("baseWarning falls back without a manifest", /re-resolved from the manifest\./.test(core.baseWarning("ours", "go.sum")));
  }

  // --- path confinement ---
  check("isInside child", core.isInside("/a/b", "/a/b/c"));
  check("isInside self", core.isInside("/a/b", "/a/b"));
  check("isInside sibling prefix rejected", !core.isInside("/a/b", "/a/bc"));
  check("isInside parent rejected", !core.isInside("/a/b", "/a"));
  check("isInside ../ rejected", !core.isInside("/a/b", path.resolve("/a/b/../x")));

  // --- real repositories ---
  const base = fs.mkdtempSync(path.join(os.tmpdir(), "ls-core-"));
  const mainRoot = makeMainRepo(path.join(base, "main"));
  const lock = path.join(mainRoot, "package-lock.json");
  check("fixture: real package-lock.json conflict", core.hasConflictMarkers(fs.readFileSync(lock, "utf8")));
  check("fixture: package.json auto-merged, no markers", !core.hasConflictMarkers(fs.readFileSync(path.join(mainRoot, "package.json"), "utf8")));
  check("fixture: packages/web/package.json conflicted (manifest refusal case)", core.hasConflictMarkers(fs.readFileSync(path.join(mainRoot, "packages/web/package.json"), "utf8")));
  check("fixture: decoy JSON string not flagged", !core.hasConflictMarkers(fs.readFileSync(path.join(mainRoot, "docs/notes.json"), "utf8")));
  const realMain = fs.realpathSync(mainRoot);
  const ctx = await core.gitContext(fs.realpathSync(lock));
  check("gitContext ok", ctx.ok && ctx.top === realMain && ctx.rel === "package-lock.json", JSON.stringify(ctx));
  const um = await core.unmergedPaths(realMain);
  check("unmerged paths listed", um.includes("package-lock.json") && um.includes("-weird/yarn.lock"), um.join(","));
  const pctx = await core.gitContext(fs.realpathSync(path.join(mainRoot, "py/poetry.lock")));
  const co = await core.checkoutSide(pctx, "ours");
  const pl = fs.readFileSync(path.join(mainRoot, "py/poetry.lock"), "utf8");
  check("checkout --ours gives our side", co.ok && !core.hasConflictMarkers(pl) && /version = "2\.1\.0"/.test(pl), co.stderr);
  const wctx = await core.gitContext(fs.realpathSync(path.join(mainRoot, "-weird/yarn.lock")));
  const wco = await core.checkoutSide(wctx, "theirs");
  check("checkout --theirs on a '-' folder", wco.ok && /1\.2\.0/.test(fs.readFileSync(path.join(mainRoot, "-weird/yarn.lock"), "utf8")), wco.stderr);
  const st = await core.stage(pctx);
  check("stage clears the unmerged entry", st.ok && !(await core.unmergedPaths(realMain)).includes("py/poetry.lock"), st.stderr);

  // --- hostile repository ---
  const outside = path.join(base, "outside");
  const markers = path.join(base, "markers");
  const hostile = makeHostileRepo(path.join(base, "hostile"), outside, markers);
  const hreal = fs.realpathSync(hostile);
  const hctx = await core.gitContext(fs.realpathSync(path.join(hostile, "Cargo.lock")));
  check("hostile: gitContext ok for Cargo.lock", hctx.ok, JSON.stringify(hctx));
  const hco = await core.checkoutSide(hctx, "ours");
  check("hostile: checkout --ours works", hco.ok && !core.hasConflictMarkers(fs.readFileSync(path.join(hostile, "Cargo.lock"), "utf8")), hco.stderr);
  const hst = await core.stage(hctx);
  check("hostile: stage works", hst.ok, hst.stderr);
  await core.unmergedPaths(hreal);
  const gctx = await core.gitContext(fs.realpathSync(path.join(hostile, "gems/Gemfile.lock")));
  check("hostile: filter attribute refused", !gctx.ok && gctx.reason === "filter-attribute", JSON.stringify(gctx));
  check("hostile: no fsmonitor/pager/extdiff/hook/filter marker created", fs.readdirSync(markers).length === 0, fs.readdirSync(markers).join(","));
  // Control: plain git WITHOUT the hardening does run the hostile config (proves the fixture bites).
  try {
    require("child_process").execFileSync("git", ["checkout", "--ours", "--", "gems/Gemfile.lock"], { cwd: hostile, env: Object.assign({}, process.env, { GIT_CONFIG_GLOBAL: "/dev/null" }), stdio: "ignore" });
  } catch (_) { /* ignore */ }
  check("control: unhardened git runs the hostile config", fs.readdirSync(markers).length > 0, "no markers from control");
  for (const f of fs.readdirSync(markers)) fs.unlinkSync(path.join(markers, f));

  const linkReal = await core.confine(path.join(hostile, "linked/package-lock.json"), [hreal]);
  check("hostile: symlinked lockfile outside is not confined", linkReal === null);
  const traversal = await core.confine(path.join(hostile, "../outside/package-lock.json"), [hreal]);
  check("hostile: ../ path is not confined", traversal === null);

  const esc = makeWorktreeEscapeRepo(path.join(base, "esc"), path.join(base, "escaped-worktree"));
  const ectx = await core.gitContext(fs.realpathSync(path.join(esc, "go.sum")));
  check("hostile: core.worktree outside refused", !ectx.ok && ectx.reason === "outside-worktree", JSON.stringify(ectx));

  const nonRepo = path.join(base, "plain");
  fs.mkdirSync(nonRepo);
  fs.writeFileSync(path.join(nonRepo, "go.sum"), "x\n");
  const nctx = await core.gitContext(fs.realpathSync(path.join(nonRepo, "go.sum")), {});
  check("non-repo refused", !nctx.ok, JSON.stringify(nctx));

  fs.rmSync(base, { recursive: true, force: true });
  console.log(`\ncore tests: ${pass} passed, ${fail} failed`);
  process.exit(fail ? 1 : 0);
}

main().catch((e) => {
  console.log("FAIL unexpected " + (e && e.stack));
  process.exit(1);
});
